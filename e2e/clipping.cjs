const { chromium, devices } = require('playwright-core')
const { rect, handle, startBox } = require('./helpers.cjs')
const out = process.env.E2E_OUT
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const near = (a, b, tolerance = 3) => Math.abs(a - b) <= tolerance
const canvasBox = page => page.$eval('#canvas', el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height, right: r.right, bottom: r.bottom } })
const shapeBox = (page, selector) => page.$eval(selector, el => { const r = el.getBoundingClientRect(); return { left: r.left, top: r.top, right: r.right, bottom: r.bottom, cx: r.left + r.width / 2, cy: r.top + r.height / 2 } })
const visibleAt = (page, x, y, selector) => page.evaluate(([x, y, selector]) => {
  const hit = document.elementFromPoint(x, y)
  return hit != null && hit.closest('#canvas') != null && (selector == null || hit.matches(selector))
}, [x, y, selector])

;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')
  const canvas = await canvasBox(page)
  const corner = { x: canvas.right - 12, y: canvas.bottom - 12 }

  const pay = await rect(page, '#canvas g.node', 'pay')
  await page.mouse.click(pay.cx, pay.cy)
  let h = await handle(page, 'node', 'pay')
  await page.mouse.move(h.x, h.y)
  await page.mouse.down()
  await page.mouse.move(corner.x, corner.y, { steps: 20 })
  let wire = await shapeBox(page, '#canvas .dc-wire')
  check('connection line reaches the far corner of the canvas', near(wire.right, corner.x) && near(wire.bottom, corner.y), JSON.stringify({ wire, corner }))
  check('connection line is visible at the corner, not hidden', await visibleAt(page, corner.x - 3, corner.y - 3) )
  await page.screenshot({ path: `${out}/clip-wire.png` })
  await page.mouse.up()
  await page.click('#undo')

  await startBox(page)
  const start = { x: canvas.right - 20, y: canvas.bottom - 20 }
  const end = { x: canvas.x + 20, y: canvas.y + 20 }
  await page.mouse.move(start.x, start.y)
  await page.mouse.down()
  await page.mouse.move(end.x, end.y, { steps: 20 })
  const marquee = await shapeBox(page, '#canvas .dc-marquee')
  check('box rectangle spans the whole canvas', near(marquee.left, end.x) && near(marquee.top, end.y) && near(marquee.right, start.x) && near(marquee.bottom, start.y), JSON.stringify(marquee))
  check('every node inside it is highlighted', (await page.$$('#canvas g.node.dc-drop')).length === 4)
  await page.screenshot({ path: `${out}/clip-marquee.png` })
  await page.mouse.up()
  await page.keyboard.press('Escape')
  await page.click('#undo')

  const done = await rect(page, '#canvas g.node', 'done')
  await page.mouse.click(done.cx, done.cy)
  const doneGrip = await handle(page, 'node', 'done', 'move')
  await page.mouse.move(doneGrip.x, doneGrip.y)
  await page.mouse.down()
  await page.mouse.move(corner.x - 60, corner.y - 30, { steps: 20 })
  const ghost = await shapeBox(page, '#canvas .dc-ghost')
  check('moving node follows the pointer to the corner', near(ghost.cx, done.cx + (corner.x - 60 - doneGrip.x), 4) && near(ghost.cy, done.cy + (corner.y - 30 - doneGrip.y), 4), JSON.stringify({ ghost, done, doneGrip }))
  await page.mouse.up()

  await page.click('#debug-toggle')
  const text = await page.$eval('#source', el => el.value)
  const many = Array.from({ length: 14 }, (_, k) => `  extra${k} [label="Step ${k}"]\n  ${k === 0 ? 'done' : `extra${k - 1}`} -> extra${k}`).join('\n')
  await page.fill('#source', text.replace(/\n}\n?$/, `\n${many}\n}\n`))
  await page.waitForTimeout(700)
  await page.click('#debug-toggle')
  await page.addStyleTag({ content: '#canvas > svg:not(.dc-overlay) { max-width: none !important; }' })
  const scrolled = await page.$eval('#canvas', el => { el.scrollLeft = el.scrollWidth; return { scrollLeft: el.scrollLeft, overflow: el.scrollWidth > el.clientWidth } })
  check('a wide diagram scrolls inside the canvas', scrolled.overflow && scrolled.scrollLeft > 0, JSON.stringify(scrolled))
  const last = await rect(page, '#canvas g.node', 'extra13')
  await page.mouse.click(last.cx, last.cy)
  h = await handle(page, 'node', 'extra13')
  const box = await canvasBox(page)
  check('after scrolling, the handle sits by the node and inside the canvas', h != null && h.x <= box.right && h.x >= box.x && Math.hypot(h.x - last.cx, h.y - last.cy) < Math.max(last.w, last.h) / 2 + 40 && await visibleAt(page, h.x, h.y, '.dc-handle-hit'), JSON.stringify({ h, last, box }))
  await page.mouse.move(h.x, h.y)
  await page.mouse.down()
  await page.mouse.move(box.x + 40, box.y + 40, { steps: 20 })
  wire = await page.$eval('#canvas .dc-wire', el => ({ x1: +el.getAttribute('x1'), y1: +el.getAttribute('y1') }))
  const startClient = await page.evaluate(([x1, y1]) => { const c = document.querySelector('#canvas'); const r = c.getBoundingClientRect(); return { x: x1 + r.left - c.scrollLeft, y: y1 + r.top - c.scrollTop } }, [wire.x1, wire.y1])
  check('in a scrolled canvas the line starts at the node', near(startClient.x, last.cx) && near(startClient.y, last.cy), JSON.stringify({ startClient, last }))
  await page.mouse.up()
  check('no page errors', errors.length === 0, errors.join('\n'))

  const phone = await (await browser.newContext({ ...devices['iPhone 13'] })).newPage()
  await phone.goto('http://localhost:8091/?doc=test&fresh')
  await phone.waitForSelector('#canvas svg g.node', { timeout: 30000 })
  const right = await rect(phone, '#canvas g.node', 'done')
  await phone.touchscreen.tap(right.cx, right.cy)
  const ph = await handle(phone, 'node', 'done')
  const pbox = await canvasBox(phone)
  check('on a phone, the right-edge node\'s handle moves inside the screen', ph != null && ph.x >= pbox.x && ph.x <= pbox.right && await visibleAt(phone, ph.x, ph.y, '.dc-handle-hit'), JSON.stringify({ ph, pbox }))
  await phone.screenshot({ path: `${out}/clip-phone.png` })
  await browser.close()
})()
