const { chromium, devices } = require('playwright-core')
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
;(async () => {
  const browser = await chromium.launch()
  const page = await (await browser.newContext({ ...devices['iPhone 13'] })).newPage()
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.cluster', { timeout: 30000 })
  const spot = await page.evaluate(() => {
    const r = document.querySelector('#canvas g.cluster').getBoundingClientRect()
    return { x: r.x + r.width / 2, y: r.y + r.height - 6 }
  })
  await page.touchscreen.tap(spot.x, spot.y)
  check('tapping inside the dashed box selects it', !(await page.$eval('#rename', b => b.disabled)) && (await page.$('button[aria-label="Color: Amber"]')) != null)
  check('delete stays off for a cluster', await page.$eval('#delete', b => b.disabled))
  await page.tap('#panel-toggle')
  await page.tap('#rename')
  await page.waitForSelector('.dc-editor')
  await page.keyboard.press('Meta+A')
  await page.keyboard.type('Shop')
  await page.keyboard.press('Enter')
  check('rename the cluster', (await page.$eval('#source', el => el.value)).includes('label=Shop'))
  await page.tap('#panel-toggle')
  await page.tap('button[aria-label="Color: Amber"]')
  check('color the cluster', (await page.$eval('#source', el => el.value)).includes('class=amber'))
  await page.tap('#drawer-close')
  const node = await page.evaluate(() => { const g = [...document.querySelectorAll('#canvas g.node')].find(g => g.querySelector('title').textContent === 'cart'); const r = g.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } })
  await page.touchscreen.tap(node.x, node.y)
  check('boxes inside the cluster still get the tap', !(await page.$eval('#delete', b => b.disabled)))
  check('no page errors', errors.length === 0, errors.join('\n'))
  await browser.close()
})()
