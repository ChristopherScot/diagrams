const { chromium } = require('playwright-core')
const { rect } = require('./helpers.cjs')
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const source = page => page.$eval('#source', el => el.value)
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')
  const pay = await rect(page, '#canvas g.node', 'pay')
  await page.mouse.click(pay.cx, pay.cy)
  await page.click('button[aria-label="Color: Rose"]')
  const again = await rect(page, '#canvas g.node', 'pay')
  await page.mouse.click(again.cx, again.cy)
  await page.keyboard.press('Tab')
  await page.waitForSelector('.dc-editor')
  await page.keyboard.type('Refund')
  await page.keyboard.press('Enter')
  let s = await source(page)
  check('Tab on a selected node adds a connected node with its look and the label open', s.includes('refund [label=Refund, class=rose]') && s.includes('pay -> refund'), s)
  check('the new node is selected, so Tab again chains', (await page.textContent('#selection')) === 'node: refund')
  await page.keyboard.press('Tab')
  await page.waitForSelector('.dc-editor')
  await page.keyboard.type('Notify')
  await page.keyboard.press('Enter')
  s = await source(page)
  check('Tab again keeps building the chain', s.includes('notify [label=Notify, class=rose]') && s.includes('refund -> notify'), s)
  await page.keyboard.press('Escape')
  const before = await source(page)
  await page.focus('#canvas')
  await page.keyboard.press('Tab')
  check('with nothing selected, Tab just moves focus', (await source(page)) === before && (await page.evaluate(() => document.activeElement.id)) !== 'canvas')
  check('no page errors', errors.length === 0, errors.join('\n'))
  await browser.close()
})()
