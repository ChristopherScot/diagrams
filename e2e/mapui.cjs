const { chromium, devices } = require('playwright-core')
const { rect, connect, handle, dragMouse } = require('./helpers.cjs')
const out = process.env.E2E_OUT
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const source = page => page.$eval('#source', el => el.value)
const crumbs = page => page.$$eval('#crumbs button:not(.delete-view)', bs => bs.map(b => b.textContent).join(' › '))
const nodes = page => page.$$eval('#canvas g.node', gs => gs.filter(g => g.classList.contains('dc-target')).map(g => g.querySelector('title').textContent).sort().join(','))
const groups = page => page.$$eval('#canvas g.cluster', gs => gs.map(g => g.querySelector('title').textContent).sort().join(','))

;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')
  const store = await rect(page, '#canvas g.cluster', 'cluster_store')
  await page.mouse.click(store.x + 6, store.y + store.h - 6)
  await page.click('#to-view')

  await page.selectOption('#view-picker', 'whole-map')
  check('Whole map is in the view picker and is not drawn as a level under a view', (await crumbs(page)) === '' && (await page.$eval('#view-picker', el => el.value)) === 'whole-map' && (await page.evaluate(() => location.hash)) === '#whole-map', await crumbs(page))
  check('it draws the child view as a group with its nodes', (await groups(page)) === 'cluster_v_store' && (await nodes(page)) === 'checkout::browse,checkout::done,store::cart,store::pay', `${await groups(page)} | ${await nodes(page)}`)
  await page.screenshot({ path: `${out}/map-all.png` })

  check('a fully open map offers one button: Collapse all', (await page.textContent('#map-toggle')) === 'Collapse all')
  await page.click('#map-toggle')
  check('then it offers Expand all', (await page.textContent('#map-toggle')) === 'Expand all')
  check('Collapse all closes everything below', (await groups(page)) === '' && (await nodes(page)) === 'checkout::browse,checkout::done,checkout::store', await nodes(page))
  const closed = await rect(page, '#canvas g.node', 'checkout::store')
  await page.mouse.click(closed.x + 2, closed.cy)
  check('clicking a closed node\'s thick border opens that branch in place', (await groups(page)) === 'cluster_v_store', await groups(page))
  const group = await rect(page, '#canvas g.cluster', 'cluster_v_store')
  await page.mouse.click(group.x + 1, group.cy)
  check('clicking a group\'s border closes it again', (await groups(page)) === '', await groups(page))
  await page.click('#map-toggle')
  check('Expand all opens everything again', (await groups(page)) === 'cluster_v_store' && (await page.textContent('#map-toggle')) === 'Collapse all', await groups(page))

  const cart = await rect(page, '#canvas g.node', 'store::cart')
  await page.mouse.dblclick(cart.cx, cart.cy)
  await page.waitForSelector('.dc-editor')
  await page.keyboard.press('Meta+A')
  await page.keyboard.type('Basket')
  await page.keyboard.press('Enter')
  let s = await source(page)
  check('renaming in the map renames it in its own view', /digraph store \{[\s\S]*basket \[label=Basket\]/.test(s), s)

  const pay = await rect(page, '#canvas g.node', 'store::pay')
  await page.mouse.click(pay.cx, pay.cy)
  await page.click('button[aria-label="Color: Blue"]')
  s = await source(page)
  check('styling in the map styles it in its own view', /digraph store \{[\s\S]*pay \[label="Payment", class=blue\]/.test(s), s)
  check('view-only controls are hidden in the map', !(await page.isVisible('#link-row')) && !(await page.isVisible('#move-row')))

  const target = await rect(page, '#canvas g.node', 'store::basket')
  await connect(page, 'node', 'checkout::done', { x: target.cx, y: target.cy })
  s = await source(page)
  check('connecting across views puts the arrow in the target view with the source coming in as a ghost', /digraph store \{[\s\S]*done \[label="Order placed", class=ghost, URL="#checkout"\][\s\S]*done -> basket/.test(s), s)
  check('the map shows the new arrow between the real nodes, no duplicate ghost', (await page.$$eval('#canvas g.edge', es => es.map(e => e.querySelector('title').textContent))).includes('checkout::done->store::basket') && !(await nodes(page)).includes('checkout::basket'), await nodes(page))

  const canvas = await page.$eval('#canvas', el => { const r = el.getBoundingClientRect(); return { right: r.right, bottom: r.bottom } })
  const before = await source(page)
  const pay2 = await rect(page, '#canvas g.node', 'store::pay')
  await page.mouse.click(pay2.cx, pay2.cy)
  const grip = await handle(page, 'node', 'store::pay', 'move')
  await dragMouse(page, grip, { x: canvas.right - 60, y: canvas.bottom - 60 })
  const moved = await source(page)
  check('dragging a node out of its view onto empty map moves it to the top view', /digraph checkout \{[\s\S]*pay \[label=(\"Payment\"|Payment)/.test(moved) && !/digraph store \{[^]*pay \[label=\"Payment\"\]/.test(moved), moved)

  await page.click('#undo')
  check('undo stays in the map', (await page.evaluate(() => location.hash)) === '#whole-map')
  check('no page errors', errors.length === 0, errors.join('\n'))

  const phone = await (await browser.newContext({ ...devices['iPhone 13'] })).newPage()
  await phone.goto('http://localhost:8091/?doc=test&fresh')
  await phone.waitForSelector('#canvas svg g.node', { timeout: 30000 })
  const ps = await rect(phone, '#canvas g.cluster', 'cluster_store')
  await phone.touchscreen.tap(ps.x + 6, ps.y + ps.h - 6)
  await phone.tap('#panel-toggle')
  await phone.tap('#to-view')
  await phone.selectOption('#view-picker', 'whole-map')
  const pg = await rect(phone, '#canvas g.cluster', 'cluster_v_store')
  await phone.touchscreen.tap(pg.x + 1, pg.cy)
  check('on a phone, tapping a group border closes it', (await groups(phone)) === '', await groups(phone))
  await phone.screenshot({ path: `${out}/map-phone.png` })
  await browser.close()
})()
