const { chromium, devices } = require('playwright-core')
const { rect, handle, dragMouse, connect, moveWithGrip } = require('./helpers.cjs')
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const source = page => page.$eval('#source', el => el.value)
const inStore = (page, node) => page.evaluate(node => {
  const store = [...document.querySelectorAll('#canvas g.cluster')].find(g => g.querySelector('title').textContent === 'cluster_store').getBoundingClientRect()
  const box = [...document.querySelectorAll('#canvas g.node')].find(g => g.querySelector('title').textContent === node).getBoundingClientRect()
  return box.left >= store.left && box.right <= store.right && box.top >= store.top && box.bottom <= store.bottom
}, node)

;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')

  let pay = await rect(page, '#canvas g.node', 'pay')
  await connect(page, 'node', 'done', { x: pay.cx, y: pay.cy })
  let s = await source(page)
  check('handle onto a node inside a box links to that node', s.includes('done -> pay\n'), s)

  const done = await rect(page, '#canvas g.node', 'done')
  const cart = await rect(page, '#canvas g.node', 'cart')
  await page.mouse.click(done.cx, done.cy)
  await page.mouse.move(done.cx, done.cy)
  await page.mouse.down()
  await page.mouse.move(cart.cx, cart.cy, { steps: 15 })
  check('the node under the drag is highlighted as the link target', await page.$eval('#canvas', c => [...c.querySelectorAll('g.node.dc-drop')].map(g => g.querySelector('title').textContent).join(',')) === 'cart')
  await page.mouse.up()
  s = await source(page)
  check('click a node, then drag from it onto a node inside a box: links them', s.includes('done -> cart\n'), s)
  check('and does not move the dragged node', !(await inStore(page, 'done')), s)

  const store = await rect(page, '#canvas g.cluster', 'cluster_store')
  const doneNow = await rect(page, '#canvas g.node', 'done')
  await moveWithGrip(page, 'done', { x: store.cx, y: store.y + 14 })
  check('the grip still moves a node into a box', await inStore(page, 'done'), await source(page))

  await page.click('#debug-toggle')
  await page.fill('#source', 'digraph inside {\n  rankdir=LR\n  subgraph cluster_a {\n    label="Inside"\n    inner [label="Plain node"]\n  }\n  outer [label="Outside"]\n}\n')
  await page.waitForTimeout(600)
  const inner = await rect(page, '#canvas g.node', 'inner')
  await connect(page, 'node', 'outer', { x: inner.cx - inner.w / 4, y: inner.cy + inner.h / 4 })
  s = await source(page)
  check('the middle of an unfilled node inside a box takes the link', s.includes('outer -> inner\n'), s)
  check('no page errors', errors.length === 0, errors.join('\n'))

  const phone = await (await browser.newContext({ ...devices['iPhone 13'] })).newPage()
  await phone.goto('http://localhost:8091/?doc=test&fresh')
  await phone.waitForSelector('#canvas svg g.node', { timeout: 30000 })
  const pd = await rect(phone, '#canvas g.node', 'done')
  const pp = await rect(phone, '#canvas g.node', 'pay')
  await phone.touchscreen.tap(pd.cx, pd.cy)
  const cdp = await phone.context().newCDPSession(phone)
  const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y }] })
  await touch('touchStart', pd.cx, pd.cy)
  for (let k = 1; k <= 12; k += 1) await touch('touchMove', pd.cx + (pp.cx - pd.cx) * k / 12, pd.cy + (pp.cy - pd.cy) * k / 12)
  await touch('touchEnd')
  await phone.waitForTimeout(200)
  check('on a phone, tap a node then drag from it onto a node inside a box: links them', (await source(phone)).includes('done -> pay\n'), await source(phone))
  await browser.close()
})()
