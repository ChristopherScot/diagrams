const { chromium, devices } = require('playwright-core')
const { rect } = require('./helpers.cjs')
const out = process.env.E2E_OUT
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const source = page => page.$eval('#source', el => el.value)
const crumbs = page => page.$$eval('#crumbs button:not(.delete-view)', bs => bs.map(b => b.textContent).join(' › '))
const nodes = page => page.$$eval('#canvas g.node', gs => gs.map(g => g.querySelector('title').textContent).sort().join(','))

;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')
  check('at the top view the name shows once, in the header', (await crumbs(page)) === '' && (await page.textContent('#diagram-name')) === 'Checkout' && (await page.$$('#view-title')).length === 0)

  const store = await rect(page, '#canvas g.cluster', 'cluster_store')
  await page.mouse.click(store.x + 6, store.y + store.h - 6)
  check('a selected box offers Turn into view', await page.isVisible('#to-view'))
  await page.click('#to-view')
  let s = await source(page)
  check('the box becomes a linked node and a new view', s.includes('store [label=Store, URL="#store"]') && s.includes('digraph store {'), s)
  check('arrows into and out of the box now use the node', s.includes('store -> done [label=paid]'), s)
  check('the new node has the thick linked border', (await page.$$('#canvas g.node.dc-linked')).length === 1)
  check('a message explains how to open it', (await page.textContent('#status')).includes('Click its thick border'))

  let node = await rect(page, '#canvas g.node', 'store')
  await page.mouse.click(node.cx, node.cy)
  check('clicking inside a linked node selects it instead of opening', (await crumbs(page)) === '' && (await page.textContent('#selection')) === 'node: store')
  await page.mouse.click(node.x + 2, node.cy)
  check('clicking its thick border opens the view', (await crumbs(page)) === 'Checkout › Store' && (await page.evaluate(() => location.hash)) === '#store', await crumbs(page))
  check('the view holds the box contents plus a ghost of what it connected to', (await nodes(page)) === 'browse,cart,pay', await nodes(page))
  const ghostDash = await page.evaluate(() => { const g = [...document.querySelectorAll('#canvas g.node')].find(n => n.querySelector('title').textContent === 'browse'); return getComputedStyle(g.querySelector('path, polygon')).strokeDasharray })
  check('the ghost is drawn dashed', ghostDash !== 'none', ghostDash)
  const ghost = await rect(page, '#canvas g.node', 'browse')
  await page.mouse.click(ghost.cx, ghost.cy)
  check('a ghost shows where it lives and no styling', (await page.$eval('#opens', s => s.value)) === 'checkout' && (await page.$eval('#style-bar', b => b.hidden)))
  await page.screenshot({ path: `${out}/views-store.png` })

  await page.click('#crumbs button:not([aria-current]):not(.delete-view)')
  check('the breadcrumb goes back up to the top view', (await crumbs(page)) === '')

  node = await rect(page, '#canvas g.node', 'store')
  await page.mouse.dblclick(node.cx, node.cy)
  await page.waitForSelector('.dc-editor')
  await page.keyboard.press('Meta+A')
  await page.keyboard.type('Shop')
  await page.keyboard.press('Enter')
  s = await source(page)
  check('renaming a linked node renames its view', s.includes('shop [label=Shop') && /digraph store \{\n  title=Shop/.test(s), s)
  await page.click('#view-picker')
  await page.selectOption('#view-picker', 'store')
  await page.click('#view-title')
  await page.fill('.title-input', 'Basket')
  await page.keyboard.press('Enter')
  s = await source(page)
  check('renaming a view in its header renames the node that opens it', s.includes('basket [label=Basket') && (await crumbs(page)) === 'Checkout › Basket', s)
  const canvasBottom = await page.$eval('#canvas', el => el.getBoundingClientRect().bottom)
  check('the caption sits under the diagram', (await page.$eval('#view-caption', el => el.getBoundingClientRect().top)) >= canvasBottom - 1)
  await page.click('#view-caption')
  await page.fill('.text-input', 'What a shopper does **before** paying.')
  await page.keyboard.press('Meta+Enter')
  check('the caption is editable', (await source(page)).includes('caption="What a shopper does **before** paying."'), await source(page))
  check('the caption renders Markdown', (await page.$eval('#view-caption', el => el.innerHTML)).includes('<strong>before</strong>'))
  await page.click('#view-notes')
  await page.fill('.text-input', 'First line\n\n- one\n- two')
  await page.keyboard.press('Meta+Enter')
  check('notes keep line breaks as \\n, like the skill', (await source(page)).includes('notes="First line\\n\\n- one\\n- two"'), await source(page))
  check('and render as a list', (await page.$eval('#view-notes', el => el.innerHTML)).includes('<ul><li>one</li><li>two</li></ul>'))
  await page.click('#crumbs button:not([aria-current]):not(.delete-view)')

  const done = await rect(page, '#canvas g.node', 'done')
  await page.mouse.click(done.cx, done.cy)
  await page.click('#add-detail')
  s = await source(page)
  check('Add detail view makes an empty child view and opens it', (await crumbs(page)) === 'Checkout › Order placed' && (await page.$$('#canvas g.node')).length === 0 && s.includes('done [label="Order placed", class=green, URL="#order-placed"]'), s)
  await page.click('#crumbs button:not([aria-current]):not(.delete-view)')
  const done2 = await rect(page, '#canvas g.node', 'done')
  await page.mouse.click(done2.cx, done2.cy)
  check('Opens shows the link', (await page.$eval('#opens', s => s.value)) === 'order-placed')
  await page.selectOption('#opens', '')
  check('Opens: Nothing removes the link', !(await source(page)).includes('URL="#order-placed"'))

  const shop = await rect(page, '#canvas g.node', 'basket')
  await page.mouse.click(shop.cx, shop.cy)
  await page.click('#delete')
  check('deleting a linked node asks what to do', (await page.textContent('#prompt')).includes('opens the view "Basket"'))
  await page.click('#prompt button.danger')
  s = await source(page)
  check('Delete node and view removes both', !s.includes('digraph store') && !s.includes('basket [label'), s)
  await page.click('#undo')
  s = await source(page)
  check('one undo brings both back', s.includes('digraph store') && s.includes('basket [label=Basket'), s)

  await page.evaluate(() => { location.hash = 'store' })
  await page.waitForTimeout(300)
  check('a #view address opens that view', (await crumbs(page)) === 'Checkout › Basket')
  await page.click('#delete-view')
  await page.click('#prompt button.danger')
  s = await source(page)
  check('Delete view removes it, unlinks its node and goes up', !s.includes('digraph store') && !s.includes('URL="#store"') && (await crumbs(page)) === '', s)
  check('no page errors', errors.length === 0, errors.join('\n'))

  const phone = await (await browser.newContext({ ...devices['iPhone 13'] })).newPage()
  await phone.goto('http://localhost:8091/?doc=test&fresh')
  await phone.waitForSelector('#canvas svg g.node', { timeout: 30000 })
  const ps = await rect(phone, '#canvas g.cluster', 'cluster_store')
  await phone.touchscreen.tap(ps.x + 6, ps.y + ps.h - 6)
  await phone.tap('#panel-toggle')
  await phone.tap('#to-view')
  const pn = await rect(phone, '#canvas g.node', 'store')
  await phone.touchscreen.tap(pn.x + 2, pn.cy)
  check('on a phone, tapping the thick border opens the view', (await crumbs(phone)) === 'Checkout › Store', await crumbs(phone))
  check('no handles are left over from the previous view', (await phone.$$('#canvas .dc-handles')).length === 0)
  await phone.screenshot({ path: `${out}/views-phone.png` })
  await browser.close()
})()
