const { chromium } = require('playwright-core')
const out = process.env.E2E_OUT
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 }, colorScheme: 'dark' })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')
  const p = await page.evaluate(() => { const g = [...document.querySelectorAll('#canvas g.node')].find(g => g.querySelector('title').textContent === 'pay'); const r = g.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } })
  await page.mouse.click(p.x, p.y)
  const groups = await page.$$eval('#style-bar .ds-label', ls => ls.map(l => l.textContent))
  check('the style bar is just Color, Shape and Line', JSON.stringify(groups) === JSON.stringify(['Color', 'Shape', 'Line']), groups.join(','))
  const names = await page.$$eval('[aria-label="Color"] button', bs => bs.map(b => b.title))
  check('Color offers only Default and the six skill classes', JSON.stringify(names) === JSON.stringify(['Default', 'Blue', 'Green', 'Amber', 'Violet', 'Rose', 'Slate']), names.join(','))
  check('there is no color wheel or other color row', (await page.$$('#style-bar input[type="color"], [aria-label="Fill"], [aria-label="Line color"], [aria-label="Text color"]')).length === 0)
  const swatch = await page.$eval('button[aria-label="Color: Blue"]', b => getComputedStyle(b).backgroundColor)
  check('dark swatch uses the tuned dark fill', swatch === 'rgb(37, 44, 75)', swatch)
  await page.click('button[aria-label="Color: Amber"]')
  const s = await page.$eval('#source', el => el.value)
  check('choosing a color writes the class', s.includes('pay [label="Payment", class=amber]'), s)
  const boxFill = await page.evaluate(() => { const g = [...document.querySelectorAll('#canvas g.node')].find(g => g.querySelector('title').textContent === 'pay'); return getComputedStyle(g.querySelector('path, polygon')).fill })
  check('dark box uses the tuned amber fill', boxFill === 'rgb(56, 42, 24)', boxFill)
  check('the chosen class is marked', await page.$eval('button[aria-label="Color: Amber"]', b => b.getAttribute('aria-pressed')) === 'true')
  await page.screenshot({ path: `${out}/playground-palette-dark.png`, clip: { x: 960, y: 90, width: 340, height: 200 } })
  check('no page errors', errors.length === 0, errors.join('\n'))
  await browser.close()
})()
