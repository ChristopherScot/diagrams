const { chromium } = require('playwright-core')
const { rect } = require('./helpers.cjs')
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
;(async () => {
  const browser = await chromium.launch()
  const context = await browser.newContext({ viewport: { width: 1300, height: 760 }, colorScheme: 'dark' })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')
  check('no theme picker', (await page.$$('[data-theme-choice]')).length === 0)
  const before = await page.$eval('#canvas', el => el.getBoundingClientRect().width)
  await page.click('#panel-toggle')
  const after = await page.$eval('#canvas', el => el.getBoundingClientRect().width)
  check('Hide panel hides the side panel and widens the canvas', !(await page.isVisible('.side')) && after > before + 200, `${before} -> ${after}`)
  check('the button now says Show panel', (await page.textContent('#panel-toggle')) === 'Show panel')
  const done = await rect(page, '#canvas g.node', 'done')
  await page.mouse.click(done.cx, done.cy)
  await page.keyboard.press('Tab')
  await page.waitForSelector('.dc-editor'); await page.keyboard.press('Enter')
  check('editing still works with the panel hidden', (await page.$eval('#source', el => el.value)).includes('done -> new_node'))
  await page.screenshot({ path: process.env.E2E_OUT + '/panel-hidden.png' })
  await page.reload(); await page.waitForSelector('#canvas svg g.node')
  check('the choice is remembered', !(await page.isVisible('.side')))
  await page.click('#panel-toggle')
  check('Show panel brings it back', await page.isVisible('.side'))
  check('no page errors', errors.length === 0, errors.join('\n'))
  await browser.close()
})()
