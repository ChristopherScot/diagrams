const { chromium } = require('playwright-core')
const { rect, handle, dragMouse, startBox } = require('./helpers.cjs')
const out = process.env.E2E_OUT
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const source = page => page.$eval('#source', el => el.value)
const parentOf = (page, cluster) => page.evaluate(cluster => {
  const boxes = [...document.querySelectorAll('#canvas g.cluster')].map(g => ({ id: g.querySelector('title').textContent, r: g.getBoundingClientRect() }))
  const me = boxes.find(b => b.id === cluster)
  const around = boxes.filter(b => b.id !== cluster && b.r.left <= me.r.left && b.r.right >= me.r.right && b.r.top <= me.r.top && b.r.bottom >= me.r.bottom)
  around.sort((a, b) => a.r.width * a.r.height - b.r.width * b.r.height)
  return around[0]?.id ?? null
}, cluster)

;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')

  const store = await rect(page, '#canvas g.cluster', 'cluster_store')
  const done = await rect(page, '#canvas g.node', 'done')
  await startBox(page)
  await dragMouse(page, { x: store.x - 12, y: store.y - 12 }, { x: done.x + done.w + 12, y: Math.max(store.y + store.h, done.y + done.h) + 12 }, 20)
  await page.waitForSelector('.dc-editor')
  await page.keyboard.type('Checkout')
  await page.keyboard.press('Enter')
  let s = await source(page)
  check('a rectangle around a whole box wraps it instead of nesting inside it', (await parentOf(page, 'cluster_store')) === 'cluster_1' && /subgraph cluster_1 \{\n    label=Checkout\n    subgraph cluster_store/.test(s), s)
  check('the wrapped box keeps its own nodes', s.includes('    cart [label="Cart"]') || /cluster_store \{[^}]*cart/.test(s), s)

  const storeNow = await rect(page, '#canvas g.cluster', 'cluster_store')
  await page.mouse.click(storeNow.x + 6, storeNow.y + storeNow.h - 6)
  const grip = await handle(page, 'cluster', 'cluster_store', 'move')
  check('a selected box shows a move grip', grip != null)
  const canvas = await page.$eval('#canvas', el => { const r = el.getBoundingClientRect(); return { right: r.right, bottom: r.bottom } })
  await dragMouse(page, grip, { x: canvas.right - 80, y: canvas.bottom - 80 })
  check('dragging a box\'s grip onto empty canvas takes it out of its parent box', (await parentOf(page, 'cluster_store')) === null, await source(page))

  const outer = await rect(page, '#canvas g.cluster', 'cluster_1')
  const storeOut = await rect(page, '#canvas g.cluster', 'cluster_store')
  await page.mouse.click(storeOut.x + 6, storeOut.y + storeOut.h - 6)
  const grip2 = await handle(page, 'cluster', 'cluster_store', 'move')
  await dragMouse(page, grip2, { x: outer.x + 10, y: outer.y + outer.h - 10 })
  check('dragging a box\'s grip into another box nests it', (await parentOf(page, 'cluster_store')) === 'cluster_1', await source(page))

  const outerNow = await rect(page, '#canvas g.cluster', 'cluster_1')
  await page.mouse.click(outerNow.x + 4, outerNow.y + outerNow.h - 4)
  const options = await page.$$eval('#move-to option', os => os.map(o => o.value))
  check('the Box menu for a box leaves out itself and the boxes inside it', !options.includes('cluster_1') && !options.includes('cluster_store') && options.includes(''), options.join(','))
  const storeIn = await rect(page, '#canvas g.cluster', 'cluster_store')
  await page.mouse.click(storeIn.x + 6, storeIn.y + storeIn.h - 6)
  check('the Box menu shows a nested box\'s parent', (await page.$eval('#move-to', el => el.value)) === 'cluster_1')
  await page.selectOption('#move-to', '')
  check('choosing No box takes the box out', (await parentOf(page, 'cluster_store')) === null, await source(page))

  await page.click('#undo')
  const inner = await rect(page, '#canvas g.cluster', 'cluster_store')
  const outer2 = await rect(page, '#canvas g.cluster', 'cluster_1')
  await page.mouse.click(outer2.x + 4, outer2.y + outer2.h - 4)
  const grip3 = await handle(page, 'cluster', 'cluster_1', 'move')
  await page.mouse.move(grip3.x, grip3.y)
  await page.mouse.down()
  await page.mouse.move(inner.x + 8, inner.y + inner.h - 8, { steps: 15 })
  check('a box is never offered as a drop target inside itself', (await page.$$('#canvas g.cluster.dc-drop')).length === 0)
  await page.mouse.up()
  check('so dropping it there changes nothing', (await parentOf(page, 'cluster_store')) === 'cluster_1', await source(page))
  await page.screenshot({ path: `${out}/nesting.png` })
  check('no page errors', errors.length === 0, errors.join('\n'))
  await browser.close()
})()
