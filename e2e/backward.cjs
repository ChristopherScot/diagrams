const { chromium } = require('playwright-core')
const { rect, handle, dragMouse } = require('./helpers.cjs')
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const source = page => page.$eval('#source', el => el.value)
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 }, colorScheme: 'dark' })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')
  let done = await rect(page, '#canvas g.node', 'done')
  await page.mouse.click(done.cx, done.cy)
  const out = await handle(page, 'node', 'done', 'connect')
  const into = await handle(page, 'node', 'done', 'connect-in')
  check('a selected node shows a dot on its left for backward arrows', into != null && out != null && into.x < done.x && out.x > done.x + done.w, JSON.stringify({ into, out, done }))
  await page.screenshot({ path: process.env.E2E_OUT + '/backward-handles.png', clip: { x: done.x - 60, y: done.y - 40, width: done.w + 120, height: done.h + 100 } })
  const browse = await rect(page, '#canvas g.node', 'browse')
  await dragMouse(page, into, { x: browse.cx, y: browse.cy })
  let s = await source(page)
  check('dragging the left dot to a node draws an arrow pointing back at it, laid out behind', s.includes('browse -> done [dir=back]'), s)
  await page.screenshot({ path: process.env.E2E_OUT + '/backward-arrow.png' })
  done = await rect(page, '#canvas g.node', 'done')
  await page.mouse.click(done.cx, done.cy)
  const into2 = await handle(page, 'node', 'done', 'connect-in')
  const canvas = await page.$eval('#canvas', el => { const r = el.getBoundingClientRect(); return { x: r.x, bottom: r.bottom } })
  await dragMouse(page, into2, { x: canvas.x + 60, y: canvas.bottom - 60 })
  await page.waitForSelector('.dc-editor'); await page.keyboard.press('Enter')
  s = await source(page)
  check('dragging the left dot to empty space makes a node behind, with the arrow pointing back at it', /new_node -> done \[dir=back\]/.test(s), s)
  done = await rect(page, '#canvas g.node', 'done')
  await page.mouse.click(done.cx, done.cy)
  await page.keyboard.press('Shift+Tab')
  await page.waitForSelector('.dc-editor'); await page.keyboard.press('Enter')
  s = await source(page)
  check('Shift+Tab does the same', /new_node_2 -> done \[dir=back\]/.test(s), s)
  await page.waitForTimeout(900)
  await page.goto('http://localhost:8091/?doc=test#whole-map')
  await page.waitForSelector('#canvas svg g.edge')
  check('the map draws it backward too', await page.$$eval('#canvas g.edge', es => es.some(e => /new_node_2/.test(e.querySelector('title').textContent) && e.querySelectorAll('polygon').length > 0)))
  check('no page errors', errors.length === 0, errors.join('\n'))
  await browser.close()
})()
