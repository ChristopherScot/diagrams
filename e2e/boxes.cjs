const { chromium, devices } = require('playwright-core')
const { connect, startBox } = require('./helpers.cjs')
const out = process.env.E2E_OUT
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const rect = (page, selector, title) => page.evaluate(([selector, title]) => {
  const g = [...document.querySelectorAll(selector)].find(g => g.querySelector('title').textContent === title)
  const r = g.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height, cx: r.x + r.width / 2, cy: r.y + r.height / 2 }
}, [selector, title])
const source = page => page.$eval('#source', el => el.value)
async function drag(page, from, to) {
  await page.mouse.move(from.x, from.y); await page.mouse.down()
  await page.mouse.move((from.x + to.x) / 2, (from.y + to.y) / 2, { steps: 6 })
  await page.mouse.move(to.x, to.y, { steps: 6 }); await page.mouse.up()
}
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')

  const done = await rect(page, '#canvas g.node', 'done')
  await startBox(page)
  await drag(page, { x: done.x - 15, y: done.y - 15 }, { x: done.x + done.w + 15, y: done.y + done.h + 15 })
  await page.waitForSelector('.dc-editor')
  await page.keyboard.type('Fulfilment')
  await page.keyboard.press('Enter')
  let s = await source(page)
  check('drag around a node makes a box with its title open', /subgraph cluster_1 \{\n    label=Fulfilment\n    class=green\n    done\n  \}/.test(s), s)
  check('the new box is drawn', (await page.$$eval('#canvas g.cluster', gs => gs.length)) === 2)

  const store = await rect(page, '#canvas g.cluster', 'cluster_store')
  const cart = await rect(page, '#canvas g.node', 'cart')
  await startBox(page)
  await drag(page, { x: cart.x - 4, y: store.y + store.h - 6 }, { x: cart.x + cart.w + 4, y: cart.y - 4 })
  await page.waitForSelector('.dc-editor')
  await page.keyboard.press('Enter')
  s = await source(page)
  check('a box drawn inside a box nests in it', /    pay \[label="Payment"\]\n    subgraph cluster_2 \{\n      label="New box"\n      cart\n    \}\n  \}/.test(s), s)

  const canvas = await page.$eval('#canvas', el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height } })
  await startBox(page)
  await drag(page, { x: canvas.x + 60, y: canvas.y + canvas.h - 160 }, { x: canvas.x + 200, y: canvas.y + canvas.h - 60 })
  await page.waitForSelector('.dc-editor')
  await page.keyboard.type('Later')
  await page.keyboard.press('Enter')
  s = await source(page)
  check('a box around nothing is empty, with no placeholder node', s.includes('subgraph cluster_3 {\n    label=Later\n    cluster_3_anchor [shape=point, style=invis, width=0, height=0, label=""]\n  }') && !s.includes('New node'), s)
  check('the empty box is drawn', (await page.$$('#canvas g.cluster')).length === 4)

  const box = await rect(page, '#canvas g.cluster', 'cluster_1')
  await connect(page, 'node', 'pay', { x: box.x + 8, y: box.y + box.h - 8 })
  s = await source(page)
  check('connecting from a node into a box links to the box', s.includes('pay -> cluster_1_anchor [lhead=cluster_1]'), s)

  await page.screenshot({ path: `${out}/boxes.png` })
  for (let k = 0; k < 6; k += 1) await page.click('#undo')
  check('undo removes the boxes again', !(await source(page)).includes('cluster_1'))
  check('no page errors', errors.length === 0, errors.join('\n'))

  const phone = await (await browser.newContext({ ...devices['iPhone 13'] })).newPage()
  await phone.goto('http://localhost:8091/?doc=test&fresh')
  await phone.waitForSelector('#canvas svg g.node', { timeout: 30000 })
  const pdone = await rect(phone, '#canvas g.node', 'done')
  const cdp = await phone.context().newCDPSession(phone)
  const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y }] })
  await phone.tap('#panel-toggle')
  await phone.tap('#new-button')
  await phone.tap('#new-box')
  await touch('touchStart', pdone.x - 8, pdone.y - 8)
  for (let k = 1; k <= 8; k += 1) await touch('touchMove', pdone.x - 8 + (pdone.w + 16) * k / 8, pdone.y - 8 + (pdone.h + 16) * k / 8)
  await touch('touchEnd')
  await phone.waitForSelector('.dc-editor')
  await phone.keyboard.press('Enter')
  check('a finger drag draws a box on a phone', (await source(phone)).includes('subgraph cluster_1'), await source(phone))
  await browser.close()
})()
