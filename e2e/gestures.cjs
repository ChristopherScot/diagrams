const { chromium, devices } = require('playwright-core')
const { rect, handle, dragMouse, connect, moveWithGrip } = require('./helpers.cjs')
const out = process.env.E2E_OUT
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const source = page => page.$eval('#source', el => el.value)
const inStore = (page, node) => page.evaluate(node => {
  const store = [...document.querySelectorAll('#canvas g.cluster')].find(g => g.querySelector('title').textContent === 'cluster_store').getBoundingClientRect()
  const box = [...document.querySelectorAll('#canvas g.node')].find(g => g.querySelector('title').textContent === node).getBoundingClientRect()
  return box.left >= store.left && box.right <= store.right && box.top >= store.top && box.bottom <= store.bottom
}, node)

;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')

  const done = await rect(page, '#canvas g.node', 'done')
  await page.mouse.move(done.cx, done.cy)
  check('hovering a node shows its handle', (await handle(page, 'node', 'done')) != null)

  const store = await rect(page, '#canvas g.cluster', 'cluster_store')
  await page.mouse.click(done.cx, done.cy)
  check('a selected node shows a move grip', (await handle(page, 'node', 'done', 'move')) != null)
  await moveWithGrip(page, 'done', { x: store.cx, y: store.y + 14 })
  let s = await source(page)
  check('dragging the grip into a box moves the node there', await inStore(page, 'done'), s)
  check('moving draws no connection', (s.match(/->/g) || []).length === 4, s)

  const cart = await rect(page, '#canvas g.node', 'cart')
  const canvas = await page.$eval('#canvas', el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height } })
  await moveWithGrip(page, 'cart', { x: canvas.x + canvas.w - 100, y: canvas.y + canvas.h - 100 })
  s = await source(page)
  check('dragging the grip out of the box takes the node out', !(await inStore(page, 'cart')) && s.includes('cart [label="Cart"]'), s)

  const storeNow = await rect(page, '#canvas g.cluster', 'cluster_store')
  await connect(page, 'node', 'cart', { x: storeNow.x + 10, y: storeNow.y + storeNow.h - 10 })
  s = await source(page)
  check('handle drag onto a box links to the box', s.includes('cart -> cluster_store_anchor [lhead=cluster_store]') && s.includes('compound=true'), s)
  const arrow = await page.evaluate(() => {
    const edge = [...document.querySelectorAll('#canvas g.edge')].find(g => g.querySelector('title').textContent.includes('cluster_store_anchor'))
    const store = [...document.querySelectorAll('#canvas g.cluster')].find(g => g.querySelector('title').textContent === 'cluster_store').getBoundingClientRect()
    const head = edge.querySelector('polygon').getBoundingClientRect()
    return { headRight: head.right, headLeft: head.left, storeLeft: store.left, storeRight: store.right }
  })
  check('the arrow stops at the box border', Math.abs(arrow.headRight - arrow.storeLeft) < 3 || Math.abs(arrow.headLeft - arrow.storeRight) < 3, JSON.stringify(arrow))

  const cartNow = await rect(page, '#canvas g.node', 'cart')
  await connect(page, 'cluster', 'cluster_store', { x: cartNow.cx, y: cartNow.cy })
  s = await source(page)
  check('a box handle links from the box', s.includes('cluster_store_anchor -> cart [ltail=cluster_store]'), s)

  const storeLast = await rect(page, '#canvas g.cluster', 'cluster_store')
  await connect(page, 'node', 'pay', { x: storeLast.x + 10, y: storeLast.y + storeLast.h - 10 })
  check('linking a node inside a box to that box is refused with a message', (await page.textContent('#status')).includes("can't be linked"), await page.textContent('#status'))

  const payNow = await rect(page, '#canvas g.node', 'pay')
  await page.mouse.click(payNow.cx, payNow.cy)
  const start = await handle(page, 'node', 'pay')
  await page.mouse.move(start.x, start.y)
  await page.mouse.down()
  const svgBottom = await page.$eval('#canvas > svg:not(.dc-overlay) g.graph', g => g.getBoundingClientRect().bottom)
  await page.mouse.move(start.x + 40, svgBottom + 20, { steps: 15 })
  const wire = await page.evaluate(() => {
    const w = document.querySelector('#canvas .dc-wire').getBoundingClientRect()
    const svg = document.querySelector('#canvas > svg:not(.dc-overlay)')
    return { wireBottom: w.bottom, svgBottom: svg.querySelector('g.graph').getBoundingClientRect().bottom, overflow: 'visible' }
  })
  await page.screenshot({ path: `${out}/wire-after.png` })
  await page.mouse.up()
  await page.keyboard.press('Escape')
  check('the connection line is not clipped past the drawing', wire.overflow === 'visible' && wire.wireBottom > wire.svgBottom, JSON.stringify(wire))
  await page.screenshot({ path: `${out}/gestures.png` })
  check('no page errors', errors.length === 0, errors.join('\n'))

  const phone = await (await browser.newContext({ ...devices['iPhone 13'] })).newPage()
  await phone.goto('http://localhost:8091/?doc=test&fresh')
  await phone.waitForSelector('#canvas svg g.node', { timeout: 30000 })
  const pd = await rect(phone, '#canvas g.node', 'done')
  await phone.touchscreen.tap(pd.cx, pd.cy)
  const ph = await handle(phone, 'node', 'done')
  check('tapping a node on a phone shows its handle', ph != null)
  const ps = await rect(phone, '#canvas g.cluster', 'cluster_store')
  const cdp = await phone.context().newCDPSession(phone)
  const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y }] })
  await touch('touchStart', ph.x, ph.y)
  for (let k = 1; k <= 10; k += 1) await touch('touchMove', ph.x + (ps.x + 12 - ph.x) * k / 10, ph.y + (ps.y + ps.h - 12 - ph.y) * k / 10)
  await touch('touchEnd')
  await phone.waitForTimeout(200)
  check('a finger on the handle links to a box', (await source(phone)).includes('done -> cluster_store_anchor [lhead=cluster_store]'), await source(phone))
  const pc = await rect(phone, '#canvas g.node', 'cart')
  await phone.touchscreen.tap(pc.cx, pc.cy)
  const grip = await handle(phone, 'node', 'cart', 'move')
  await touch('touchStart', grip.x, grip.y)
  for (let k = 1; k <= 10; k += 1) await touch('touchMove', grip.x, grip.y + 300 * k / 10)
  await touch('touchEnd')
  await phone.waitForTimeout(200)
  check('a finger on the grip moves a node out of its box', !(await inStore(phone, 'cart')), await source(phone))
  await browser.close()
})()
