const { chromium } = require('playwright-core')
const { rect } = require('./helpers.cjs')
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const source = page => page.$eval('#source', el => el.value)
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')
  const store = await rect(page, '#canvas g.cluster', 'cluster_store')
  await page.mouse.click(store.x + 6, store.y + store.h - 6)
  await page.click('#to-view')
  await page.selectOption('#view-picker', 'whole-map')
  await page.waitForTimeout(300)
  const cart = await rect(page, '#canvas g.node', 'store::cart')
  await page.mouse.click(cart.cx, cart.cy)
  await page.keyboard.press('Tab')
  await page.waitForSelector('.dc-editor', { timeout: 3000 }).catch(() => {})
  check('Tab on the map opens the new node\'s label', (await page.$('.dc-editor')) != null, await page.textContent('#status'))
  await page.keyboard.type('Tabbed')
  await page.keyboard.press('Enter')
  let s = await source(page)
  check('Tab adds a connected node in that node\'s view', /digraph store \{[\s\S]*cart -> tabbed[\s\S]*/.test(s) && /digraph store \{[\s\S]*label=Tabbed/.test(s), s)
  const pay = await rect(page, '#canvas g.node', 'store::pay')
  const canvas = await page.$eval('#canvas', el => { const r = el.getBoundingClientRect(); return { right: r.right, bottom: r.bottom } })
  await page.mouse.move(pay.cx, pay.cy); await page.mouse.down()
  await page.mouse.move(pay.cx + 40, pay.cy + 40, { steps: 5 })
  await page.mouse.move(canvas.right - 60, canvas.bottom - 60, { steps: 10 })
  await page.mouse.up()
  await page.waitForSelector('.dc-editor', { timeout: 3000 }).catch(() => {})
  check('dragging an arrow out to empty space on the map makes a node', (await page.$('.dc-editor')) != null, await page.textContent('#status'))
  await page.keyboard.type('Dragged')
  await page.keyboard.press('Enter')
  s = await source(page)
  check('and connects it in that view', /digraph store \{[\s\S]*label=Dragged[\s\S]*pay -> dragged/.test(s), s)
  check('no page errors', errors.length === 0, errors.join('\n'))
  await browser.close()
})()
