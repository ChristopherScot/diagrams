const { chromium } = require('playwright-core')
const center = (page, selector, title) => page.evaluate(([selector, title]) => {
  const g = [...document.querySelectorAll(selector)].find(g => g.querySelector('title').textContent === title)
  const t = selector.includes('node') ? g : (g.querySelector('text') || g)
  const r = t.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }
}, [selector, title])
const source = page => page.$eval('#source', el => el.value)
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')
  const typeOn = async (selector, title, text) => {
    const p = await center(page, selector, title)
    await page.mouse.click(p.x, p.y)
    await page.keyboard.type(text)
    await page.keyboard.press('Enter')
    return source(page)
  }
  let s = await typeOn('#canvas g.edge', 'pay->done', 'Paid in full')
  check('type on an arrow', s.includes('pay -> done [label="Paid in full"]'), s)
  s = await typeOn('#canvas g.node', 'cart', 'Basket')
  check('type on a box', s.includes('basket [label=Basket]'), s)
  s = await typeOn('#canvas g.cluster', 'cluster_store', 'Shop')
  check('type on a cluster', s.includes('label=Shop'), s)
  const p = await center(page, '#canvas g.node', 'pay')
  await page.mouse.click(p.x, p.y)
  await page.keyboard.press('Meta+z')
  s = await source(page)
  check('shortcuts still go to undo, not the label', s.includes('label="Store"') && !s.includes('label=z'), s)
  await page.mouse.click(p.x, p.y)
  await page.keyboard.type('X')
  await page.keyboard.press('Escape')
  s = await source(page)
  check('Esc cancels typed label', s.includes('pay [label="Payment"]'), s)
  check('no page errors', errors.length === 0, errors.join('\n'))
  await browser.close()
})()
