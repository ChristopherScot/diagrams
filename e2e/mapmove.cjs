const { chromium } = require('playwright-core')
const fs = require('fs')
const { rect, handle, dragMouse } = require('./helpers.cjs')
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const source = page => page.$eval('#source', el => el.value)
;(async () => {
  fs.copyFileSync(__dirname + '/fixtures/map.dot', process.env.DIAGRAMS_DIR + '/bugs.dot')
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1500, height: 860 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=bugs#whole-map')
  await page.waitForSelector('#canvas svg g.node')
  await page.waitForTimeout(400)
  check('the orphaned ghost is repaired on load', (await source(page)).includes('URL="#not-so-fun-stuff"'))
  const stray = await page.$$eval('#canvas g.node', gs => gs.filter(g => !g.querySelector('text') && !/anchor/.test(g.querySelector('title').textContent)).map(g => g.querySelector('title').textContent))
  check('no phantom nodes on the map', stray.length === 0, stray.join(','))
  const id = await page.$$eval('#canvas g.node', gs => gs.find(g => g.querySelector('text')?.textContent === 'test')?.querySelector('title').textContent)
  const node = await rect(page, '#canvas g.node', id)
  await page.mouse.click(node.cx, node.cy)
  const grip = await handle(page, 'node', id, 'move')
  const fun = await rect(page, '#canvas g.cluster', 'cluster_v_fun-stuff')
  await dragMouse(page, grip, { x: fun.x + 20, y: fun.y + fun.h - 15 })
  await page.waitForTimeout(300)
  const s = await source(page)
  check('dragging "test" into fun stuff moves it into that view', /digraph "fun-stuff" \{[\s\S]*label=test/.test(s), (await page.textContent('#status')) + '\n' + s.slice(-900))
  await page.screenshot({ path: process.env.E2E_OUT + '/mapmove.png' })
  check('no page errors', errors.length === 0, errors.join('\n'))
  await browser.close()
})()
