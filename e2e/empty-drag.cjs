const { chromium, devices } = require('playwright-core')
const { rect, dragMouse, startBox } = require('./helpers.cjs')
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const source = page => page.$eval('#source', el => el.value)
const url = process.argv[2] ?? 'http://localhost:8091/?doc=test&fresh'

;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 } })
  const events = []
  await page.exposeFunction('logEvent', e => events.push(e))
  await page.goto(url)
  await page.waitForSelector('#canvas svg g.node', { timeout: 30000 })
  await page.evaluate(() => { for (const type of ['pointerdown', 'pointermove', 'pointerup', 'pointercancel']) document.querySelector('#canvas').addEventListener(type, e => { if (type !== 'pointermove') window.logEvent(`${type}:${e.target.tagName}.${e.target.getAttribute('class') ?? ''}`) }, true) })
  const canvas = await page.$eval('#canvas', el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height, right: r.right, bottom: r.bottom } })
  const done = await rect(page, '#canvas g.node', 'done')
  await dragMouse(page, { x: canvas.right - 30, y: canvas.bottom - 30 }, { x: done.x - 10, y: done.y - 10 }, 20)
  check('desktop: dragging on empty space without the box tool does nothing', !(await source(page)).includes('subgraph cluster_1') && (await page.$$('#canvas .dc-marquee')).length === 0)
  await startBox(page)
  check('choosing New then Box turns the button into Cancel box and explains what to do', (await page.textContent('#new-button')) === 'Cancel box' && (await page.textContent('#status')).startsWith('Drag around'))
  await page.click('#new-button')
  check('Cancel box leaves box mode', (await page.textContent('#new-button')) === '+ New')
  await startBox(page)
  await page.focus('#canvas')
  await page.keyboard.press('Escape')
  check('Esc also leaves box mode', (await page.textContent('#new-button')) === '+ New')
  await startBox(page)
  await dragMouse(page, { x: canvas.right - 30, y: canvas.bottom - 30 }, { x: done.x - 10, y: done.y - 10 }, 20)
  const editor = await page.$('.dc-editor')
  if (editor) await page.keyboard.press('Enter')
  check('box mode ends after one box', (await page.textContent('#new-button')) === '+ New')
  check('desktop: drag from far empty canvas around a node makes a box', (await source(page)).includes('subgraph cluster_1'), events.join('\n'))

  await startBox(page)
  await page.mouse.click(canvas.right - 40, canvas.bottom - 40)
  if (await page.$('.dc-editor')) await page.keyboard.press('Enter')
  check('a tap in box mode makes an empty box', (await source(page)).includes('cluster_2_anchor'), await source(page))

  const phone = await (await browser.newContext({ ...devices['iPhone 13'] })).newPage()
  const phoneEvents = []
  await phone.exposeFunction('logEvent', e => phoneEvents.push(e))
  await phone.goto(url)
  await phone.waitForSelector('#canvas svg g.node', { timeout: 30000 })
  await phone.evaluate(() => { for (const type of ['pointerdown', 'pointerup', 'pointercancel']) document.querySelector('#canvas').addEventListener(type, e => window.logEvent(`${type}:${e.target.tagName}.${e.target.getAttribute('class') ?? ''}`), true) })
  const pc = await phone.$eval('#canvas', el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height, right: r.right, bottom: r.bottom } })
  const pd = await rect(phone, '#canvas g.node', 'done')
  const cdp = await phone.context().newCDPSession(phone)
  const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y }] })
  const from = { x: pc.right - 20, y: pc.bottom - 40 }
  const to = { x: pd.x - 6, y: pd.y - 6 }
  await phone.tap('#panel-toggle')
  await phone.tap('#new-button')
  await phone.tap('#new-box')
  await touch('touchStart', from.x, from.y)
  for (let k = 1; k <= 12; k += 1) await touch('touchMove', from.x + (to.x - from.x) * k / 12, from.y + (to.y - from.y) * k / 12)
  await touch('touchEnd')
  await phone.waitForTimeout(300)
  if (await phone.$('.dc-editor')) await phone.keyboard.press('Enter')
  check('phone: finger drag from empty canvas around a node makes a box', (await source(phone)).includes('subgraph cluster_1'), phoneEvents.join('\n'))
  await browser.close()
})()
