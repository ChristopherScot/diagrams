const { chromium, devices } = require('playwright-core')
const out = process.env.E2E_OUT
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
;(async () => {
  const browser = await chromium.launch()
  const context = await browser.newContext({ ...devices['iPhone 13'], colorScheme: 'dark' })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => m.type() === 'error' && errors.push(m.text()))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node', { timeout: 30000 })
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
  check('no sideways scrolling on a phone', overflow <= 0, String(overflow))
  const box = await page.evaluate(() => { const g = [...document.querySelectorAll('#canvas g.node')].find(g => g.querySelector('title').textContent === 'pay'); const r = g.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 } })
  await page.touchscreen.tap(box.x, box.y)
  check('the panel starts closed behind a menu button on a phone', !(await page.isVisible('.side')) && (await page.getAttribute('#panel-toggle', 'aria-expanded')) === 'false')
  await page.tap('#panel-toggle')
  check('the menu button opens the panel as a drawer', await page.isVisible('.side') && await page.isVisible('#scrim'))
  check('tap selects and enables Rename', !(await page.$eval('#rename', b => b.disabled)))
  await page.tap('#rename')
  check('Rename closes the drawer so the label can be edited', !(await page.isVisible('.side')))
  await page.waitForSelector('.dc-editor')
  await page.keyboard.press('Meta+A')
  await page.keyboard.type('Pay now')
  await page.keyboard.press('Enter')
  const text = await page.$eval('#source', el => el.value)
  check('rename from the button', text.includes('pay [label="Pay now"]'), text)
  await page.tap('#panel-toggle')
  await page.tap('button[aria-label="Color: Green"]')
  check('style from the panel', (await page.$eval('#source', el => el.value)).includes('pay [label="Pay now", class=green]'))
  await page.tap('#new-button')
  await page.tap('#new-node')
  await page.waitForSelector('.dc-editor')
  await page.keyboard.type('Refund')
  await page.keyboard.press('Enter')
  check('add box from the button', (await page.$eval('#source', el => el.value)).includes('refund [label=Refund]'), await page.$eval('#source', el => el.value))
  await page.tap('#panel-toggle')
  await page.tap('#delete')
  check('delete from the button', !(await page.$eval('#source', el => el.value)).includes('refund ['))
  await page.screenshot({ path: `${out}/phone-dark.png`, fullPage: false })
  check('no page errors', errors.length === 0, errors.join('\n'))
  await browser.close()
})()
