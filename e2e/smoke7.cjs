const { chromium } = require('playwright-core')
const out = process.env.E2E_OUT
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const center = (page, title) => page.evaluate(title => {
  const g = [...document.querySelectorAll('#canvas g.node')].find(g => g.querySelector('title').textContent === title)
  const r = g.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }
}, title)
;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')
  check('DOT is hidden by default', !(await page.isVisible('#source')))
  await page.screenshot({ path: `${out}/playground-hidden.png` })
  await page.click('#debug-toggle')
  check('Show DOT reveals it', await page.isVisible('#source'))

  const before = await page.$eval('#source', el => el.value)
  const svgBefore = await page.$eval('#canvas svg', el => el.outerHTML.length)
  await page.fill('#source', before.replace('cart -> pay', 'cart -> '))
  await page.waitForTimeout(500)
  check('typed broken DOT is refused', (await page.textContent('#status')).startsWith('Not changed:'), await page.textContent('#status'))
  check('the diagram keeps the last valid version', (await page.$eval('#canvas svg', el => el.outerHTML.length)) === svgBefore)
  check('the field is marked', await page.$eval('#source', el => el.classList.contains('invalid')))

  await page.fill('#source', before.replace('pay [label="Payment"]', 'pay [label=<<b>Payment</b>>]'))
  await page.waitForTimeout(500)
  check('valid typed DOT is accepted', (await page.textContent('#status')) === '' && !(await page.$eval('#source', el => el.classList.contains('invalid'))), await page.textContent('#status'))
  const accepted = await page.$eval('#source', el => el.value)

  const p = await center(page, 'pay')
  await page.mouse.dblclick(p.x, p.y)
  await page.waitForSelector('.dc-editor')
  await page.keyboard.press('Meta+A')
  await page.keyboard.type('<b>Payment')
  await page.keyboard.press('Enter')
  const status = await page.textContent('#status')
  check('a canvas edit Graphviz rejects is refused', status.startsWith('Not changed:'), status)
  console.log('   message: ' + status)
  check('the text is unchanged after the refused edit', (await page.$eval('#source', el => el.value)) === accepted)

  await page.mouse.dblclick(p.x, p.y)
  await page.waitForSelector('.dc-editor')
  await page.keyboard.press('Meta+A')
  await page.keyboard.type('<i>Pay</i>')
  await page.keyboard.press('Enter')
  check('a valid canvas edit still works and clears the message', (await page.$eval('#source', el => el.value)).includes('pay [label=<<i>Pay</i>>]') && (await page.textContent('#status')) === '')
  await page.click('#undo')
  check('undo goes back through the document', (await page.$eval('#source', el => el.value)) === accepted)
  check('no page errors', errors.length === 0, errors.join('\n'))
  await browser.close()
})()
