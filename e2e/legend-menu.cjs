const { chromium } = require('playwright-core')
const { rect } = require('./helpers.cjs')
const out = process.env.E2E_OUT
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const source = page => page.$eval('#source', el => el.value)
const menu = page => page.$$eval('#context-menu button', bs => bs.map(b => b.textContent))

;(async () => {
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 760 }, colorScheme: 'dark' })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/?doc=test&fresh')
  await page.waitForSelector('#canvas svg g.node')
  check('the legend shows the classes used in this view', JSON.stringify(await page.$$eval('#legend button', bs => bs.map(b => b.dataset.class))) === '["green"]', await page.$$eval('#legend button', bs => bs.map(b => b.dataset.class).join(',')))

  const pay = await rect(page, '#canvas g.node', 'pay')
  await page.mouse.click(pay.cx, pay.cy)
  await page.click('button[aria-label="Color: Blue"]')
  check('using a class adds an unnamed chip for it', await page.$eval('#legend button[data-class="blue"]', b => b.textContent === 'Blue' && b.classList.contains('unnamed')))
  await page.click('#legend button[data-class="blue"]')
  await page.keyboard.type('Catalog')
  await page.keyboard.press('Enter')
  let s = await source(page)
  check('naming the chip writes the skill\'s legend attribute', s.includes('legend="blue: Catalog"'), s)
  check('the chip shows the name', (await page.textContent('#legend button[data-class="blue"]')) === 'Catalog')
  const pay2 = await rect(page, '#canvas g.node', 'pay')
  await page.mouse.click(pay2.cx, pay2.cy)
  check('the Color swatch shows the legend name', (await page.getAttribute('button[aria-label="Color: Blue"]', 'title')) === 'Blue: Catalog')
  await page.click('#legend button[data-class="blue"]')
  await page.keyboard.press('Meta+A')
  await page.keyboard.press('Backspace')
  await page.keyboard.press('Enter')
  check('clearing the name removes the entry', !(await source(page)).includes('legend='))
  await page.click('#legend button[data-class="blue"]')
  await page.keyboard.type('Catalog')
  await page.keyboard.press('Enter')
  const strip = await page.$eval('#legend', el => { const r = el.getBoundingClientRect(); return { x: r.x - 8, y: r.y - 60, width: 520, height: r.height + 70 } })
  await page.screenshot({ path: `${out}/legend.png`, clip: strip })

  const canvas = await page.$eval('#canvas', el => { const r = el.getBoundingClientRect(); return { right: r.right, bottom: r.bottom } })
  await page.mouse.click(canvas.right - 100, canvas.bottom - 100, { button: 'right' })
  check('right-clicking empty space offers New node, New box and From another view', JSON.stringify(await menu(page)) === JSON.stringify(['New node', 'New box', 'From another view…']), (await menu(page)).join(','))
  await page.keyboard.press('Escape')
  check('Esc closes the menu', !(await page.isVisible('#context-menu')))
  await page.mouse.click(canvas.right - 100, canvas.bottom - 100, { button: 'right' })
  await page.click('#context-menu button[data-action="new-node"]')
  await page.waitForSelector('.dc-editor')
  await page.keyboard.type('From menu')
  await page.keyboard.press('Enter')
  check('New node from the menu adds a node with its label open', (await source(page)).includes('from_menu [label="From menu"]'), await source(page))

  const cart = await rect(page, '#canvas g.node', 'cart')
  await page.mouse.click(cart.cx, cart.cy, { button: 'right' })
  check('right-clicking a node offers node actions first', JSON.stringify((await menu(page)).slice(0, 3)) === JSON.stringify(['New connected node', 'Rename', 'Delete']), (await menu(page)).join(','))
  await page.click('#context-menu button[data-action="connected"]')
  await page.waitForSelector('.dc-editor')
  await page.keyboard.press('Enter')
  check('New connected node connects from that node', (await source(page)).includes('cart -> new_node'), await source(page))

  const store = await rect(page, '#canvas g.cluster', 'cluster_store')
  await page.mouse.click(store.x + 8, store.y + store.h - 8, { button: 'right' })
  check('inside a box the menu offers a node in that box', (await menu(page)).includes('New node in this box'))
  await page.click('#context-menu button[data-action="new-node"]')
  await page.waitForSelector('.dc-editor')
  await page.keyboard.press('Enter')
  check('and puts it in the box', /subgraph cluster_store \{[^}]*new_node_2 \[label="New node"\]/.test(await source(page)), await source(page))

  await page.mouse.click(canvas.right - 100, canvas.bottom - 100, { button: 'right' })
  await page.click('#context-menu button[data-action="new-box"]')
  check('New box from the menu turns on box drawing', (await page.textContent('#new-button')) === 'Cancel box')
  await page.click('#new-button')
  check('no page errors', errors.length === 0, errors.join('\n'))
  await browser.close()
})()
