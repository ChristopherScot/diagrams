const { chromium } = require('playwright-core')
const fs = require('fs')
const path = require('path')
const check = (name, ok, detail = '') => console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${ok ? '' : '\n' + detail}`)
const dir = process.env.DIAGRAMS_DIR
const files = () => fs.readdirSync(dir).filter(name => name.endsWith('.dot')).sort()
const titles = page => page.$$eval('.card-title', els => els.map(el => el.textContent))
;(async () => {
  for (const name of fs.readdirSync(dir)) fs.rmSync(path.join(dir, name), { recursive: true, force: true })
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1300, height: 800 }, colorScheme: 'dark' })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('http://localhost:8091/')
  await page.waitForSelector('#library:not([hidden])')
  check('with no diagram chosen, the library opens, empty', await page.isVisible('#library-empty') && (await page.textContent('#library-where')).includes('diagrams server'))

  await page.click('#library-new-empty')
  await page.waitForSelector('.name-input')
  check('New diagram opens the editor with its name ready to type', !(await page.isVisible('#library')) && files().length === 1)
  const id = files()[0].slice(0, -4)
  await page.fill('.name-input', 'Payments flow')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(900)
  check('naming it keeps the id and gives the link a readable part', JSON.stringify(files()) === `["${id}.dot"]` && page.url().endsWith(`/d/${id}-payments-flow#main`), files().join(',') + ' ' + page.url())
  check('the header shows the name, once', (await page.textContent('#diagram-name')) === 'Payments flow' && (await page.$$('#view-title')).length === 0 && (await page.textContent('#crumbs')).trim() === '')
  await page.click('#new-button'); await page.click('#new-node')
  await page.waitForSelector('.dc-editor')
  await page.keyboard.type('Charge'); await page.keyboard.press('Enter')
  await page.waitForTimeout(900)
  check('edits autosave to the server', fs.readFileSync(path.join(dir, `${id}.dot`), 'utf8').includes('charge [label=Charge]'))
  check('the footer says where', (await page.textContent('#saved')) === 'Saved to the diagrams server', await page.textContent('#saved'))

  await page.click('#to-library')
  await page.waitForSelector('.card')
  check('← Diagrams goes back to the library with a card for it', JSON.stringify(await titles(page)) === '["Payments flow"]' && (await page.textContent('.card-sub')).startsWith('1 view'))
  check('the card has a drawing of the diagram', (await page.$$('.card .thumb svg g.node')).length === 1)
  await page.screenshot({ path: process.env.E2E_OUT + '/library.png' })

  await page.click('.card-menu'); await page.click('#context-menu button[data-action="rename"]')
  await page.fill('.card-rename', 'Billing'); await page.keyboard.press('Enter')
  await page.waitForTimeout(400)
  check('Rename from the card renames the diagram, same id', JSON.stringify(await titles(page)) === '["Billing"]' && JSON.stringify(files()) === `["${id}.dot"]`, files().join(','))
  check('and the name lives in the DOT as the top view title', fs.readFileSync(path.join(dir, `${id}.dot`), 'utf8').includes('title=Billing'))

  await page.click('.card-menu'); await page.click('#context-menu button[data-action="duplicate"]')
  await page.waitForTimeout(400)
  check('Duplicate makes a copy with its own id', (await titles(page)).sort().join(',') === 'Billing,Billing copy' && files().length === 2, (await titles(page)).join(','))
  await page.fill('#library-search', 'copy')
  await page.waitForTimeout(300)
  check('search filters the cards', JSON.stringify(await titles(page)) === '["Billing copy"]')
  await page.click('.card-menu'); await page.click('#context-menu button[data-action="delete"]')
  await page.waitForSelector('#prompt:not([hidden])')
  await page.click('#prompt button.danger')
  await page.waitForTimeout(300)
  await page.fill('#library-search', '')
  await page.waitForTimeout(200)
  check('Delete asks, then moves the file to the trash', JSON.stringify(await titles(page)) === '["Billing"]' && fs.readdirSync(path.join(dir, '.trash')).length === 1, (await titles(page)).join(','))

  fs.writeFileSync(path.join(process.env.E2E_OUT, 'import-me.dot'), 'digraph shop {\n  title="Shop floor"\n  a [label=Aisle]\n  b [label=Till]\n  a -> b\n}\n')
  await page.setInputFiles('#library-file', path.join(process.env.E2E_OUT, 'import-me.dot'))
  await page.waitForSelector('#library[hidden]', { state: 'attached' })
  await page.waitForTimeout(300)
  check('Import .dot adds it and opens it', files().length === 2 && (await page.textContent('#diagram-name')) === 'Shop floor' && /-shop-floor#shop$/.test(page.url()), page.url())
  await page.goBack()
  await page.waitForSelector('#library:not([hidden])')
  check('the browser Back button returns to the library', (await titles(page)).length === 2)

  await page.goto(`http://localhost:8091/d/${id}-whatever-it-was-called`)
  await page.waitForSelector('#canvas svg g.node')
  check('a /d/ link opens that diagram whatever its readable part says', (await page.textContent('#diagram-name')) === 'Billing')
  await page.goto('http://localhost:8091/d/zzzz-nope')
  await page.waitForSelector('#library:not([hidden])')
  check('a missing diagram falls back to the library with a note', (await page.textContent('#library-note')).includes('no diagram'))

  const phone = await (await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage()
  await phone.goto('http://localhost:8091/')
  await phone.waitForSelector('.card')
  const overflow = await phone.evaluate(() => document.documentElement.scrollWidth - innerWidth)
  check('the library fits a phone', overflow <= 0, String(overflow))
  await phone.screenshot({ path: process.env.E2E_OUT + '/library-phone.png' })
  check('no page errors', errors.length === 0, errors.join('\n'))
  await browser.close()
})()
